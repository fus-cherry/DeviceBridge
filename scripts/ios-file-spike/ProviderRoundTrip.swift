import DeviceBridgeCore
import Foundation

/// Explicit real-provider characterization. Only a fresh CoreDevice temporary domain is written;
/// never a target application's documents or phone photos. The 64 KiB fixture is disposable.
@main struct ProviderRoundTrip {
    static func main() async {
        do {
            let env = ProcessInfo.processInfo.environment
            guard env["DEVICEBRIDGE_FILE_ROUNDTRIP"] == "1",
                  let transport = env["DEVICEBRIDGE_FILE_TRANSPORT"],
                  let root = env["DEVICEBRIDGE_FILE_EVIDENCE"] else { throw Failure.input }
            let directory = URL(fileURLWithPath: root, isDirectory: true)
            let domain = "dev.debugutility.acceptance." + UUID().uuidString
            try Data(domain.utf8).write(to: directory.appendingPathComponent("temporary-domain.txt"), options: .withoutOverwriting)
            let bytes = Data((0..<65536).map { UInt8($0 % 251) })
            let source = directory.appendingPathComponent("fixture.bin")
            try bytes.write(to: source, options: .withoutOverwriting)
            let location = try DeviceFileLocation(scope: .iOSTemporary(identifier: domain), relativePath: "fixture.bin")
            let provider = IOSFileProvider(xcrunURL: URL(fileURLWithPath: "/usr/bin/xcrun"),
                runner: EvidenceRunner(directory: directory))
            let sent = try await provider.send(localURL: source, destination: location,
                transportID: transport, operationID: UUID(), replaceExisting: false)
            guard sent.byteLength == 65536 else { throw Failure.length }
            print("PASS: real temporary-domain send returned the expected length")
            let received = directory.appendingPathComponent("received.bin")
            let receipt = try await provider.receive(source: location, localPartialURL: received,
                transportID: transport, operationID: UUID())
            guard receipt.byteLength == 65536, try Data(contentsOf: received) == bytes else { throw Failure.bytes }
            print("PASS: real temporary-domain receive matched all 65536 generated bytes")
        } catch let error as IOSFileProviderError {
            print("FAIL: real iOS file provider category \(error)"); exit(1)
        } catch { print("FAIL: local setup or file-integrity check"); exit(1) }
    }
    enum Failure: Error { case input, length, bytes }
}

private struct EvidenceRunner: HostCommandRunning {
    let directory: URL
    func run(_ request: HostCommandRequest) async throws -> HostCommandResult {
        let result = try await HostCommandRunner().run(request)
        if let flag = request.arguments.firstIndex(of: "--json-output"), flag + 1 < request.arguments.count {
            let source = URL(fileURLWithPath: request.arguments[flag + 1])
            if FileManager.default.fileExists(atPath: source.path) {
                try FileManager.default.copyItem(at: source,
                    to: directory.appendingPathComponent(UUID().uuidString + ".json"))
            }
        }
        print("OBSERVED: scoped CoreDevice file command exit \(result.exitCode)")
        return result
    }
}
